"""Local folder opening is explicit, non-destructive and isolated per project."""

import json
from urllib.error import HTTPError
from urllib.request import Request, urlopen

import pytest

from tuba.project import load_project
from tuba.studio_launcher import StudioLauncher, create_project, local_folder


def request(launcher, route, body=None, **headers):
    data = json.dumps(body).encode("utf-8") if body is not None else None
    if data is not None:
        headers.setdefault("Content-Type", "application/json")
    req = Request(launcher.base_url + route.lstrip("/"), data=data, headers=headers)
    try:
        response = urlopen(req, timeout=10)
    except HTTPError as exc:
        response = exc
    with response:
        return response.status, json.loads(response.read())


def test_new_project_is_authored_and_loads_the_existing_code_aster_study(tmp_path):
    root = tmp_path / "Müller pipe project"
    create_project(root)
    project = load_project(root)
    model = project.run_model()["model"]
    assert len(model.elements) == 1
    assert len(model.supports) == 1
    assert project.load_settings().operations == ("Operating",)
    assert "with model.pipe(" in project.model_path.read_text(encoding="utf-8")
    assert "generated by Tuba MCP" not in project.model_path.read_text(encoding="utf-8")
    before = {path.name: path.read_bytes() for path in root.iterdir()}
    with pytest.raises(ValueError, match="new or empty"):
        create_project(root)
    assert before == {path.name: path.read_bytes() for path in root.iterdir()}


def test_open_preserves_project_files_and_reuses_only_the_same_full_root(tmp_path):
    first, second = [tmp_path / parent / "same name" for parent in ("first", "second")]
    for root in (first, second):
        root.parent.mkdir()
        create_project(root)
    before = {str(path): path.read_bytes() for root in (first, second) for path in root.iterdir()}
    launcher = StudioLauncher(tmp_path / "state").start()
    try:
        a = launcher.open_project(str(first))
        again = launcher.open_project(str(first))
        b = launcher.open_project(str(second))
        assert a["project_root"] == str(first.resolve())
        assert again["viewer_url"] == a["viewer_url"] and again["reused"]
        assert a["project_id"] != b["project_id"]
        assert a["viewer_url"] != b["viewer_url"]
        assert len(launcher._studios) == 2
        assert len({server.out_dir for server in launcher._studios.values()}) == 2
        assert [entry["path"] for entry in launcher.recent()] == [str(second.resolve()), str(first.resolve())]
        for server in launcher._studios.values():
            assert server.launcher_url == launcher.base_url
        assert before == {str(path): path.read_bytes() for root in (first, second) for path in root.iterdir() if path.is_file()}
    finally:
        launcher.stop()


def test_open_of_project_without_study_does_not_scaffold_it(tmp_path):
    root = tmp_path / "plain authored"
    root.mkdir()
    (root / "model.py").write_text('from tuba import Model\nmodel = Model("plain")\n', encoding="utf-8")
    launcher = StudioLauncher(tmp_path / "state").start()
    try:
        launcher.open_project(str(root))
        assert not (root / "study.py").exists()
        assert (root / "model.py").read_text(encoding="utf-8") == 'from tuba import Model\nmodel = Model("plain")\n'
    finally:
        launcher.stop()


def test_invalid_paths_and_stale_recent_entries_cannot_create_projects(tmp_path):
    launcher = StudioLauncher(tmp_path / "state")
    for value in ["", "relative/path", str(tmp_path / ".." / "other"), "\\\\server\\share", "//server/share", "x\x00", "x" * 4097, None]:
        with pytest.raises(ValueError):
            local_folder(value)
    missing = tmp_path / "missing"
    launcher.state_dir.mkdir()
    (launcher.state_dir / "recent.json").write_text(json.dumps([str(missing), "bad-relative"]), encoding="utf-8")
    assert launcher.recent() == [{"path": str(missing.resolve()), "name": "missing", "available": False}]
    with pytest.raises(FileNotFoundError):
        launcher.open_project(str(missing))
    assert not missing.exists()
    with pytest.raises(ValueError, match="parent folder"):
        create_project(missing / "child")
    assert not missing.exists()


def test_local_folder_browser_and_http_boundaries(tmp_path):
    parent = tmp_path / "spaces ü"
    parent.mkdir()
    create_project(parent / "project ü")
    destination = tmp_path / "should not be created"
    launcher = StudioLauncher(tmp_path / "state").start()
    try:
        from urllib.parse import quote
        status, result = request(launcher, "/api/folders?path=" + quote(str(parent)))
        assert status == 200
        assert result["folders"] == [{"name": "project ü", "path": str((parent / "project ü").resolve()), "is_project": True}]
        for headers in [{"Origin": "https://foreign.example"}, {"Host": "foreign.example"}, {"Sec-Fetch-Site": "cross-site"}]:
            status, result = request(launcher, "/api/projects/new", {"path": str(destination)}, **headers)
            assert status == 403 and not result["ok"]
        assert not destination.exists() and not launcher.state_dir.exists()
        for body in [{"path": "relative"}, {"path": str(destination), "extra": 1}, [str(destination)], {"path": "x" * 9000}]:
            status, _ = request(launcher, "/api/projects/new", body)
            assert status == 400
        assert not destination.exists()
        status, _ = request(launcher, "/api/projects/new", {"path": str(destination)}, Origin=launcher.base_url.rstrip("/"))
        assert status == 200 and destination.joinpath("model.py").is_file()
    finally:
        launcher.stop()


def test_launcher_rejects_non_loopback_host(tmp_path):
    with pytest.raises(ValueError, match="localhost"):
        StudioLauncher(tmp_path / "state", host="0.0.0.0")
