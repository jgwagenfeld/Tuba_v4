def test_replay_as_main_stamps_imported_records_with_the_call_line(tmp_path: Path, monkeypatch):
    (tmp_path / "units").mkdir()
    (tmp_path / "units" / "rack.py").write_text(POSTS, encoding="utf-8")
    monkeypatch.syspath_prepend(str(tmp_path))
    script = tmp_path / "model.py"
    script.write_text(
        '"""Tuba v4 procedural pipeline script generated by Tuba MCP."""\n\n'
        "from tuba.model import TubaModel\n"
        "from tuba.assemblies import assemble\n"
        "from units.rack import posts\n\n"
        "model = TubaModel(project_name='Units')\n"
        "assemble(model, 'units.rack:posts', x0=0.0, n=1)\n",
        encoding="utf-8",
    )
    model = run_model_script(script)["model"]
    call_line = next(
        index for index, line in enumerate(script.read_text(encoding="utf-8").splitlines(), start=1)
        if line.startswith("assemble(model,")
    )
    assert model.nodes["N0"].source_line == call_line


def test_repeated_steps_replay_as_a_loop(tmp_path: Path):
    model = _model()
    model.add_pipe_section("DN100", OD=0.1143, WT=0.00602)
    with model.pipe(section="DN100", material="Steel") as builder:
        builder.start([0.0, 0.0, 0.0], support="anchor")
        for _ in range(5):
            builder.run(2.0)
        builder.end(support="anchor")

    script = tmp_path / "model.py"
    script.write_text('"""Tuba v4 procedural pipeline script generated by Tuba MCP."""\nmodel = None\n', encoding="utf-8")
    text = write_model_script(script, model, last_text=script.read_text(encoding="utf-8"))
    assert "    for _ in range(5):\n        builder.run(2.0)" in text
    assert same_model(run_model_script(script)["model"], model)


