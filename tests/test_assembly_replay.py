def test_invocation_record_shape_is_owned_by_script():
    import tuba.assemblies
    import tuba.mcp.server
    import tuba.project.script as script

    for name in ("call_span", "format_call", "owned_records", "range_skipped"):
        assert callable(getattr(script, name)), name
        assert not hasattr(tuba.assemblies, name), name
    for name in ("prologue_namespace", "project_on_path"):
        assert callable(getattr(script, name)), name
    assert not hasattr(tuba.mcp.server, "_prologue_namespace")
    assert not hasattr(tuba.mcp.server, "_project_on_path")


def test_prologue_segments_ignores_the_header_and_keeps_order():
    text = (
        '"""Tuba v4 procedural pipeline script generated by Tuba MCP."""\n\n'
        "import os\nfrom units.rack import posts\n\n"
        "def helper(model):\n    pass\n\n"
        "model = TubaModel(project_name='X')\n"
    )
    assert _prologue_segments(text) == ["import os", "from units.rack import posts", "def helper(model):\n    pass"]
    assert _prologue_segments(None) == []
