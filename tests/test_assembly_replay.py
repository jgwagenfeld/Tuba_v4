def test_partially_overlapping_spans_are_refused(tmp_path: Path):
    model = _model()
    namespace: dict = {}
    exec(POSTS, namespace)
    assemble(model, "posts", _namespace=namespace, x0=0.0, n=4)
    model.add_support("N0", "anchor")
    # A forged call crossing the recorded spans (nodes inside, supports outside)
    # cannot replay exactly.
    model.assembly_calls.append(
        {"ref": "other", "params": {}, "node0": 1, "element0": 0, "support0": 0,
         "node1": 3, "element1": 0, "support1": 1}
    )
    script = tmp_path / "model.py"
    script.write_text('"""Tuba v4 procedural pipeline script generated by Tuba MCP."""\nmodel = None\n', encoding="utf-8")
    with pytest.raises(ValueError, match="overlap"):
        generate_model_script(model)


