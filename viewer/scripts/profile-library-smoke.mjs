// Run against a disposable Studio project: this check edits and runs model.py.
import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { chromium, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

const url = process.argv[2];
if (!url) throw new Error("Pass a disposable Studio URL.");
const output = resolve(process.argv[3] ?? "../.build/studio-profiles/browser");
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto(url);
  const editor = page.locator("[data-code-text]");
  const open = page.locator("[data-profiles-open]");
  const drawer = page.locator("[data-profile-library]");
  await expect(open).toBeVisible();
  const original = await editor.inputValue();
  const at = original.indexOf("with model.pipe");
  assert.ok(at > 0, "Disposable project needs a procedural pipe definition.");
  await editor.focus();
  await editor.evaluate((node, at) => node.setSelectionRange(at + 3, at + 3), at);
  await open.click();
  await expect(drawer).toBeVisible();
  await expect(drawer.locator("[data-profiles-status]")).toHaveText("400 profiles");
  await drawer.locator("[data-profiles-family]").selectOption("HEB");
  await expect(drawer.locator("[data-profiles-list] button").first()).toContainText("HE");
  await drawer.locator("[data-profiles-family]").selectOption("IPE");
  await drawer.locator("[data-profiles-min]").fill("150");
  await drawer.locator("[data-profiles-max]").fill("170");
  await drawer.locator("[data-profiles-search]").fill("ipe 160");
  await expect(drawer.locator("[data-profiles-list] button")).toHaveCount(1);
  await expect(drawer.locator("[data-profiles-name]")).toHaveText("IPE160");
  await expect(drawer.locator("[data-profiles-figure] svg")).toBeVisible();
  await expect(drawer.locator("[data-profiles-properties]")).toContainText("thin-wall estimate");
  await drawer.locator("[data-profiles-section-name]").fill("DN100");
  await drawer.getByRole("button", { name: "Insert into Python" }).click();
  await expect(drawer).toBeVisible();
  assert.equal(await editor.inputValue(), original);
  await drawer.locator("[data-profiles-section-name]").fill("LibraryBeam");
  const a11y = await new AxeBuilder({ page }).include("[data-profile-library]").analyze();
  assert.deepEqual(a11y.violations.map(row => ({ id: row.id, nodes: row.nodes.map(node => node.target) })), []);
  await drawer.locator("[data-profiles-preview]").evaluate(node => { node.scrollTop = 0; });
  await page.screenshot({ path: resolve(output, "profile-library.png") });
  await drawer.getByRole("button", { name: "Insert into Python" }).click();
  await expect(drawer).not.toBeVisible();
  const definition = 'model.add_ibeam_section("LibraryBeam", profile_name="IPE160")\n';
  assert.equal(await editor.inputValue(), original.slice(0, at) + definition + original.slice(at));
  await open.click();
  await expect(drawer.locator("[data-profiles-status]")).toHaveText("400 profiles");
  await drawer.getByRole("button", { name: "Used in this model" }).click();
  await expect(drawer.locator("[data-profiles-definition-note]")).toContainText("last successful run");
  await expect(drawer.locator("[data-profiles-reveal]")).toBeDisabled();
  await page.keyboard.press("Escape");
  await expect(drawer).not.toBeVisible();
  await page.locator("[data-code-run]").click();
  await expect(page.locator("[data-code-foot]")).toContainText("Saved to model.py", { timeout: 30_000 });
  await open.click();
  await expect(drawer.locator("[data-profiles-status]")).toHaveText("400 profiles");
  await drawer.getByRole("button", { name: "Used in this model" }).click();
  await drawer.locator('[data-profile-name="LibraryBeam"]').click();
  await expect(drawer.locator("[data-profiles-name]")).toHaveText("LibraryBeam · IPE160");
  await expect(drawer.locator("[data-profiles-reveal]")).toBeEnabled();
  await drawer.locator("[data-profiles-reveal]").click();
  await expect(editor).toBeFocused();
  assert.equal(await editor.evaluate(node => node.selectionStart), at);
  await open.click();
  await expect(drawer.locator("[data-profiles-status]")).toHaveText("400 profiles");
  await drawer.locator("[data-profiles-family]").selectOption("Pipe");
  await expect(drawer.locator("[data-profiles-list] button")).toHaveCount(226);
  await drawer.locator("[data-profiles-search]").fill("DN150_SCH40");
  await expect(drawer.locator("[data-profiles-list] button")).toHaveCount(1);
  await expect(drawer.locator("[data-profiles-list]")).toContainText("NPS 6 · Sch 40 · OD 168.3 × WT 7.11 mm");
  await expect(drawer.locator("[data-profiles-figure] svg")).toBeVisible();
  await expect(drawer.locator("[data-profiles-properties]")).toContainText("7.11 mm");
  await expect(drawer.locator("[data-profiles-source]")).toContainText("ASME B36.10");
  assert.deepEqual((await new AxeBuilder({ page }).include("[data-profile-library]").analyze()).violations.map(row => row.id), []);
  await drawer.locator("[data-profiles-section-name]").fill("LibraryPipe");
  await page.screenshot({ path: resolve(output, "dn-profile-library.png") });
  await drawer.getByRole("button", { name: "Insert into Python" }).click();
  const pipeDefinition = 'model.add_pipe_section("LibraryPipe", OD=0.1683, WT=0.00711)\n';
  await expect(editor).toHaveValue(original.slice(0, at) + pipeDefinition + definition + original.slice(at));
  // Route the authored pipe with the inserted section, then reload it in Studio.
  await editor.fill((await editor.inputValue()).replace('section="DN100"', 'section="LibraryPipe"'));
  await page.locator("[data-code-run]").click();
  await expect(page.locator("[data-code-foot]")).toContainText("Saved to model.py", { timeout: 30_000 });
  await open.click();
  await expect(drawer.locator("[data-profiles-status]")).toHaveText("400 profiles");
  await drawer.getByRole("button", { name: "Used in this model" }).click();
  await drawer.locator('[data-profile-name="LibraryPipe"]').click();
  await expect(drawer.locator("[data-profiles-name]")).toHaveText("LibraryPipe");
  await expect(drawer.locator("[data-profiles-reveal]")).toBeEnabled();
  await drawer.locator("[data-profiles-reveal]").click();
  assert.equal(await editor.evaluate(node => node.selectionStart), at);
  // Select through the actual object control, then inspect the member shortcut.
  await page.locator('[data-object-id="object:element:pipe_str_0"]').evaluate(node => node.click());
  const browse = page.getByRole("button", { name: "Browse profiles" });
  await expect(browse).toBeVisible();
  await browse.click();
  await expect(drawer.locator('[data-profiles-tab="used"]')).toHaveAttribute("aria-pressed", "true");
  await expect(drawer.locator("[data-profiles-name]")).toHaveText("LibraryPipe");
  await drawer.locator("[data-profiles-close]").click();
  await page.setViewportSize({ width: 390, height: 844 });
  await open.click();
  await expect(drawer.locator("[data-profiles-status]")).toHaveText("400 profiles");
  await drawer.locator("[data-profiles-search]").fill("DN150_SCH40");
  await expect(drawer.locator("[data-profiles-name]")).toHaveText("DN150_SCH40");
  assert.ok(await drawer.evaluate(node => node.scrollWidth <= node.clientWidth + 1));
  await page.screenshot({ path: resolve(output, "profile-library-mobile.png") });
  assert.deepEqual(errors, []);
  writeFileSync(resolve(output, "evidence.json"), JSON.stringify({ catalog: 400, pipeProfiles: 226, insertion: true, pipeInsertion: true, pipeRouting: true, run: true, sourceNavigation: true, memberShortcut: true, mobile: true, axeViolations: 0, pageErrors: errors }, null, 2));
  console.log("Profiles: catalog, filters, preview, insertion, Run, source navigation, keyboard, mobile, Axe passed.");
} finally {
  await browser.close();
}
